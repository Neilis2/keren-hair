document.addEventListener('DOMContentLoaded', () => {
  const form = document.getElementById('booking-form');
  const languageSelect = document.getElementById('language-select');
  const genderSelect = document.getElementById('gender-select');
  const styleSelect = document.getElementById('style-select');
  const referenceField = document.getElementById('reference-photo-field');
  const referenceInput = document.getElementById('fotoReferencia');
  const dialog = document.getElementById('style-dialog');
  const dialogTitle = document.getElementById('dialog-title');
  const dialogDescription = document.getElementById('dialog-description');
  const dialogDuration = document.getElementById('dialog-duration');
  const selectDialog = document.getElementById('select-dialog');
  const selectDialogTitle = document.getElementById('select-dialog-title');
  const selectOptions = document.getElementById('select-options');
  const styleCards = Array.from(document.querySelectorAll('.style-card'));
  const stylePlaceholder = styleSelect?.querySelector('option[value=""]');
  let currentLanguage = 'es';
  let activeCard = null;
  let selectDialogCloseTimer;

  const text = (key) => translations[currentLanguage][key] || translations.es[key] || key;

  const syncSelectTrigger = (select) => {
    const trigger = select._selectTrigger;
    if (!trigger) return;
    trigger.textContent = select.selectedOptions[0]?.textContent.trim() || '';
    trigger.classList.toggle('is-placeholder', !select.value);
    const label = select.closest('label');
    trigger.setAttribute('aria-label',
      label?.querySelector('.label-text')?.textContent.trim()
      || label?.getAttribute('aria-label')
      || select.getAttribute('aria-label')
      || '');
  };

  const closeSelectDialog = () => {
    if (!selectDialog?.open) return;
    selectDialog.classList.add('is-closing');
    window.clearTimeout(selectDialogCloseTimer);
    selectDialogCloseTimer = window.setTimeout(() => selectDialog.close(), 180);
  };

  const openSelectDialog = (select) => {
    if (!selectDialog || !selectDialogTitle || !selectOptions) return;
    window.clearTimeout(selectDialogCloseTimer);
    selectDialog.classList.remove('is-closing');
    selectOptions.replaceChildren();
    const label = select.closest('label');
    selectDialogTitle.textContent = label?.querySelector('.label-text')?.textContent.trim()
      || label?.getAttribute('aria-label')
      || select.getAttribute('aria-label')
      || '';
    Array.from(select.options).forEach((option) => {
      if (option.disabled) return;
      const button = document.createElement('button');
      button.type = 'button';
      button.className = 'select-option';
      button.textContent = option.textContent.trim();
      button.setAttribute('role', 'option');
      button.setAttribute('aria-selected', String(option.selected));
      button.addEventListener('click', () => {
        select.value = option.value;
        select.dispatchEvent(new Event('change', { bubbles: true }));
        closeSelectDialog();
      });
      selectOptions.append(button);
    });
    if (selectDialog.open) selectDialog.close();
    selectDialog.showModal();
  };

  document.querySelectorAll('select').forEach((select) => {
    const trigger = document.createElement('button');
    trigger.type = 'button';
    trigger.className = 'select-trigger';
    trigger.setAttribute('aria-haspopup', 'dialog');
    trigger.setAttribute('aria-controls', 'select-dialog');
    select._selectTrigger = trigger;
    select.classList.add('select-native');
    select.tabIndex = -1;
    select.setAttribute('aria-hidden', 'true');
    select.insertAdjacentElement('afterend', trigger);
    trigger.addEventListener('click', () => openSelectDialog(select));
    select.addEventListener('change', () => syncSelectTrigger(select));
    syncSelectTrigger(select);
  });

  selectDialog?.addEventListener('click', (event) => {
    if (event.target === selectDialog) closeSelectDialog();
  });
  selectDialog?.addEventListener('cancel', (event) => {
    event.preventDefault();
    closeSelectDialog();
  });
  selectDialog?.addEventListener('close', () => {
    selectDialog.classList.remove('is-closing');
  });

  const saveLanguage = (language) => {
    try {
      localStorage.setItem('keren-hair-language', language);
    } catch {
      // The selected language still works when storage is unavailable.
    }
  };

  const translatePage = () => {
    document.documentElement.lang = currentLanguage;
    document.querySelectorAll('[data-i18n]').forEach((element) => {
      element.textContent = text(element.dataset.i18n);
    });
    document.querySelectorAll('[data-i18n-attr]').forEach((element) => {
      element.dataset.i18nAttr.split(',').forEach((attribute) => {
        const [name, key] = attribute.split(':');
        if (name && key) element.setAttribute(name, text(key));
      });
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
      element.placeholder = text(element.dataset.i18nPlaceholder);
    });
    document.querySelectorAll('[data-i18n-aria-label]').forEach((element) => {
      element.setAttribute('aria-label', text(element.dataset.i18nAriaLabel));
    });
    document.title = text('pageTitle');
    const metaDescription = document.querySelector('meta[name="description"]');
    if (metaDescription) metaDescription.content = text('metaDescription');
    if (activeCard) showStyleDetails(activeCard);
    populateStyleOptions(styleSelect?.value);
    updateReferenceRequirement();
    document.querySelectorAll('select').forEach(syncSelectTrigger);
  };

  const getStyleName = (card) => text(card.dataset.styleKey) || card.dataset.style;

  function showStyleDetails(card) {
    dialogTitle.textContent = getStyleName(card);
    dialogDescription.textContent = text(card.dataset.descriptionKey);
    dialogDuration.textContent = text(card.dataset.durationKey);
  }

  function populateStyleOptions(previousValue = '') {
    if (!styleSelect || !stylePlaceholder) return;
    styleSelect.replaceChildren(stylePlaceholder);
    stylePlaceholder.textContent = text(genderSelect?.value ? 'selectOption' : 'selectStyleFirst');
    stylePlaceholder.selected = true;
    if (!genderSelect?.value) {
      syncSelectTrigger(styleSelect);
      return;
    }

    const matchingCards = styleCards.filter((card) => card.closest('.portfolio-group')?.dataset.audience === genderSelect.value);
    matchingCards.forEach((card) => {
      const index = styleCards.indexOf(card);
      const option = document.createElement('option');
      const price = card.querySelector('.style-info small')?.textContent.trim();
      option.value = String(index);
      option.textContent = price ? `${getStyleName(card)} — ${price}` : getStyleName(card);
      styleSelect.append(option);
    });
    if (matchingCards.some((card) => String(styleCards.indexOf(card)) === previousValue)) {
      styleSelect.value = previousValue;
    }
    syncSelectTrigger(styleSelect);
  }

  const updateReferenceRequirement = () => {
    const needsReference = genderSelect?.value === 'child';
    referenceField?.classList.toggle('is-required', needsReference);
    if (referenceInput) referenceInput.required = needsReference;
    const referenceLabel = referenceField?.querySelector('[data-i18n="referencePhotoLabel"]');
    if (referenceLabel) referenceLabel.textContent = text(needsReference ? 'referencePhotoRequired' : 'referencePhotoLabel');
  };

  const getSelectedText = (name) => {
    const select = form.elements.namedItem(name);
    return select?.selectedOptions?.[0]?.textContent.trim() || '';
  };

  const locale = () => ({ es: 'es-ES', nl: 'nl-NL', en: 'en-GB' })[currentLanguage];

  document.querySelectorAll('.style-card').forEach((card) => {
    card.addEventListener('click', () => {
      activeCard = card;
      showStyleDetails(card);
      dialog.showModal();
    });
  });

  document.querySelector('.dialog-close')?.addEventListener('click', () => dialog.close());
  dialog?.addEventListener('click', (event) => {
    if (event.target === dialog) dialog.close();
  });
  document.querySelector('[data-i18n="bookThisStyle"]')?.addEventListener('click', () => {
    if (!activeCard) return;
    genderSelect.value = activeCard.closest('.portfolio-group').dataset.audience;
    genderSelect.dispatchEvent(new Event('change'));
    styleSelect.value = String(styleCards.indexOf(activeCard));
    dialog.close();
  });

  genderSelect?.addEventListener('change', () => {
    populateStyleOptions();
    updateReferenceRequirement();
  });

  languageSelect?.addEventListener('change', () => {
    if (!translations[languageSelect.value]) return;
    currentLanguage = languageSelect.value;
    saveLanguage(currentLanguage);
    translatePage();
  });

  let savedLanguage;
  try {
    savedLanguage = localStorage.getItem('keren-hair-language');
  } catch {
    savedLanguage = null;
  }
  const browserLanguage = navigator.language?.slice(0, 2);
  currentLanguage = translations[savedLanguage] ? savedLanguage
    : translations[browserLanguage] ? browserLanguage : 'es';
  if (languageSelect) languageSelect.value = currentLanguage;
  translatePage();
  updateReferenceRequirement();

  if (!form) return;

  form.addEventListener('submit', (event) => {
    event.preventDefault();

    const formData = new FormData(form);
    const nombre = (formData.get('nombre') || '').toString().trim();
    const whatsapp = (formData.get('whatsapp') || '').toString().trim();
    const largoCabello = (formData.get('largoCabello') || '').toString().trim();
    const detallesEstilo = (formData.get('detallesEstilo') || '').toString().trim();
    const fecha = (formData.get('fecha') || '').toString().trim();
    const usoFoto = formData.get('usoFoto') === 'on';
    const menor = formData.get('menor') === 'on';
    const requiredValues = [nombre, whatsapp.replace(/\D/g, ''), genderSelect?.value, getSelectedText('tipoCabello'),
      largoCabello, styleSelect?.value, detallesEstilo, fecha];

    if (requiredValues.some((value) => !value)) {
      alert(text('validationError'));
      return;
    }
    if (genderSelect.value === 'child' && !referenceInput?.files.length) {
      alert(text('photoRequiredError'));
      referenceInput?.focus();
      return;
    }

    const date = new Date(`${fecha}T00:00:00Z`);
    const formattedDate = Number.isNaN(date.getTime())
      ? fecha
      : new Intl.DateTimeFormat(locale(), { day: '2-digit', month: '2-digit', year: 'numeric', timeZone: 'UTC' }).format(date);
    const selectedCard = styleCards[Number(styleSelect.value)];
    const styleName = selectedCard ? getStyleName(selectedCard) : '';
    const lines = [
      text('messageGreeting'),
      '',
      `${text('messageName')}: ${nombre}`,
      `${text('messageWhatsapp')}: ${whatsapp}`,
      `${text('messageHairType')}: ${getSelectedText('tipoCabello')}`,
      `${text('messageHairLength')}: ${largoCabello}`,
      `${text('messageStyle')}: ${styleName}`,
      `${text('messageDetails')}: ${detallesEstilo}`,
      `${text('messageDate')}: ${formattedDate}`,
      `${text('messagePhotoConsent')}: ${usoFoto ? text('yes') : text('no')}`,
      `${text('messageMinor')}: ${menor ? text('yes') : text('no')}`
    ];

    const message = encodeURIComponent(lines.join('\n'));
    const phone = whatsapp.replace(/\D/g, '');
    window.open(`https://wa.me/${phone}?text=${message}`, '_blank');
  });
});
